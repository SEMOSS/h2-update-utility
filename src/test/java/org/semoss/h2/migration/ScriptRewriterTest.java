    @Test
    void rewriteInPlaceReplacesAcrossMultipleLinesAndReturnsCount() throws IOException {
        Path script = tempDir.resolve("export.sql");
        Files.writeString(script, String.join("\n",
                "CREATE TABLE A(ID INT, TS DATETIME);",
                "CREATE TABLE B(NOTES LONGVARCHAR);",
                "INSERT INTO A VALUES(1, '2021-01-01 00:00:00');",  // string literal — untouched
                "INSERT INTO A VALUES(2, 'DATETIME');",              // string literal — untouched
                "CREATE TABLE C(ID IDENTITY);",
                ""), StandardCharsets.UTF_8);

        int count = ScriptRewriter.rewriteInPlace(script);
        assertEquals(3, count);

        String rewritten = Files.readString(script, StandardCharsets.UTF_8);
        assertTrue(rewritten.contains("TS TIMESTAMP"));
        assertTrue(rewritten.contains("NOTES VARCHAR"));
        assertTrue(rewritten.contains("ID BIGINT GENERATED BY DEFAULT AS IDENTITY"));
        assertTrue(rewritten.contains("'2021-01-01 00:00:00'"));
        assertTrue(rewritten.contains("'DATETIME'"));

        // Backup exists because replacements were applied
        Path backup = script.resolveSibling("export.sql.pre-rewrite.bak");
        assertTrue(Files.exists(backup));
    }

