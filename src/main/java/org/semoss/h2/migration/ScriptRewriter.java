package org.semoss.h2.migration;

import java.io.BufferedReader;
import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

/**
 * Rewrites an H2 1.x SCRIPT TO dump so that constructs H2 2.x no longer recognises are
 * translated to their modern equivalents before RUNSCRIPT FROM … FROM_1X.
 *
 * <p>Category A — legacy data-type aliases (DATETIME → TIMESTAMP, etc.) — are replaced
 * via word-boundary regex outside string/identifier literals.
 * Legacy text LOB aliases additionally use a stateful column-declaration scanner
 * to preserve CLOB semantics without rewriting TEXT identifiers or multiline data.
 *
 * <p>Category B — reserved keywords. Most are handled at the target URL with
 * {@code NON_KEYWORDS=…}, but H2 2.x does not allow {@code ROW} to be suppressed
 * (upstream h2database/h2database#3390), so a bare {@code ROW} used as a column
 * identifier is quoted into {@code "ROW"} here. The negative look-ahead keeps row-value
 * constructors ({@code ROW(1,2,3)}) and functions like {@code ROW_NUMBER()} untouched.
 *
 * <p>Category C — custom aggregates. {@code CREATE AGGREGATE} statements are emitted
 * into the SCRIPT dump verbatim, but the target H2 2.x driver's isolated classloader
 * cannot resolve the aggregate's implementation class. Rather than fail at import,
 * the rewriter strips these statements and records them as {@code strippedAggregates}
 * in the {@link RewriteReport}. Semoss re-registers {@code SMSS_MEDIAN} on first
 * connection, so end-state correctness is preserved.
 *
 * <p>The rewrite is safe with respect to user data: all replacements skip single-quoted
 * string literals and double-quoted identifiers, so a column named {@code "DATETIME"}
 * or a row containing {@code 'the DATETIME column'} round-trips unchanged.
 */
public final class ScriptRewriter {

    private static final Logger LOGGER = LogManager.getLogger(ScriptRewriter.class);

    /**
     * Legacy → modern type token replacements (Category A + B ROW).
     *
     * <p>{@code IDENTITY} and {@code ROW} both use a negative look-ahead so function
     * calls ({@code IDENTITY()}, {@code ROW(…)}) are left alone.
     */
    static final Map<Pattern, String> TYPE_ALIASES = buildAliasMap();

    /** Key names used in the {@link RewriteReport#replacementsByToken()} map. */
    static final List<String> ALIAS_ORDER = List.of(
            "DATETIME", "LONGVARCHAR", "LONGVARBINARY", "TEXT", "LONGTEXT",
            "MEDIUMTEXT", "TINYTEXT", "NTEXT", "MEDIUMBLOB", "TINYBLOB",
            "NUMBER", "IDENTITY", "ROW");

    /**
     * {@code CREATE AGGREGATE [IF NOT EXISTS] <name> FOR '<class>'} — matches the
     * single-line form emitted by H2 1.x {@code SCRIPT TO}. The class name is captured
     * for the strip-report; in practice it's almost always
     * {@code prerna.ds.rdbms.h2.H2MedianAggregation} (the {@code SMSS_MEDIAN} aggregate).
     */
    static final Pattern CREATE_AGGREGATE = Pattern.compile(
            "^\\s*CREATE\\s+AGGREGATE\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?" +
                    "(?<name>[\"]?[A-Za-z_][A-Za-z0-9_]*[\"]?)" +
                    "\\s+FOR\\s+[\"']?(?<class>[^\"';]+)[\"']?\\s*;?\\s*$",
            Pattern.CASE_INSENSITIVE);

    /** Patterns that should be noted as warnings (non-blocking observations). */
    private static final Map<Pattern, String> OBSERVATION_PATTERNS = buildObservationMap();

    private static Map<Pattern, String> buildAliasMap() {
        Map<Pattern, String> m = new LinkedHashMap<>();
        int flags = Pattern.CASE_INSENSITIVE;
        m.put(Pattern.compile("\\bDATETIME\\b", flags), "TIMESTAMP");
        m.put(Pattern.compile("\\bLONGVARCHAR\\b", flags), "VARCHAR");
        m.put(Pattern.compile("\\bLONGVARBINARY\\b", flags), "VARBINARY");
        // Text LOB aliases are handled only in column type positions, with
        // lexical state across lines (see LegacyTextTypeRewriter).
        m.put(Pattern.compile("\\bMEDIUMBLOB\\b", flags), "BLOB");
        m.put(Pattern.compile("\\bTINYBLOB\\b", flags), "BLOB");
        m.put(Pattern.compile("\\bNUMBER\\b", flags), "NUMERIC");
        m.put(Pattern.compile("\\bIDENTITY\\b(?!\\s*\\()", flags),
                "BIGINT GENERATED BY DEFAULT AS IDENTITY");
        // ROW as a bare identifier — quote it. Negative look-ahead keeps ROW(…) constructor
        // and ROW_NUMBER() untouched (the latter because of \b).
        m.put(Pattern.compile("\\bROW\\b(?!\\s*\\()", flags), "\"ROW\"");
        return m;
    }

    private static Map<Pattern, String> buildObservationMap() {
        Map<Pattern, String> m = new LinkedHashMap<>();
        int flags = Pattern.CASE_INSENSITIVE;
        m.put(Pattern.compile("^\\s*CREATE\\s+(OR\\s+REPLACE\\s+)?VIEW\\b", flags),
                "CREATE VIEW present — 2.x may re-parse expressions; MODE=LEGACY covers most legacy grammar");
        m.put(Pattern.compile("^\\s*CREATE\\s+(?:FORCE\\s+)?TRIGGER\\b", flags),
                "CREATE TRIGGER present — trigger class must be on the post-migration classpath");
        m.put(Pattern.compile("^\\s*CREATE\\s+ALIAS\\b", flags),
                "CREATE ALIAS present — alias target class must be on the post-migration classpath");
        m.put(Pattern.compile("^\\s*CREATE\\s+SEQUENCE\\b", flags),
                "CREATE SEQUENCE present — 2.x rejects CACHE 1; verify sequence options");
        m.put(Pattern.compile("\\bGROUP_CONCAT\\b", flags),
                "GROUP_CONCAT found — relies on MODE=LEGACY at runtime");
        m.put(Pattern.compile("\\bCASEWHEN\\s*\\(", flags),
                "CASEWHEN(…) found — relies on MODE=LEGACY at runtime");
        return m;
    }

    /** Token name (for report keys) mapped to the replacement's readable form. */
    static String tokenFor(Pattern p) {
        String s = p.pattern();
        // "\\bDATETIME\\b" → "DATETIME"
        int from = s.indexOf("\\b") + 2;
        int to = s.indexOf("\\b", from);
        return (from >= 2 && to > from) ? s.substring(from, to) : s;
    }

    /**
     * Structured outcome of a rewrite pass. Fed into {@link MigrationReport}
     * as {@code transformations} and {@code warnings}.
     */
    public record RewriteReport(
            int totalReplacements,
            Map<String, Integer> replacementsByToken,
            List<String> strippedAggregates,
            List<String> warnings,
            long scriptSizeBytes,
            long lineCount
    ) {
        public RewriteReport {
            replacementsByToken = Collections.unmodifiableMap(new TreeMap<>(replacementsByToken));
            strippedAggregates = List.copyOf(strippedAggregates);
            warnings = List.copyOf(warnings);
        }
    }

    private ScriptRewriter() {
    }

    /**
     * Rewrite the script in place (Category A + B ROW + C aggregates), writing the
     * transformed output back to the same path. A {@code .pre-rewrite.bak} sibling is
     * created so the original export is preserved when changes are applied.
     *
     * @param script path to the SCRIPT TO output
     * @return total number of token replacements applied (excludes aggregate strips)
     * @throws IOException if the file cannot be read or written
     */
    public static int rewriteInPlace(Path script) throws IOException {
        return rewriteAndScanInPlace(script).totalReplacements();
    }

    /**
     * Like {@link #rewriteInPlace(Path)} but returns a rich report describing every
     * modification for inclusion in {@link MigrationReport}.
     */
    public static RewriteReport rewriteAndScanInPlace(Path script) throws IOException {
        Path backup = script.resolveSibling(script.getFileName().toString() + ".pre-rewrite.bak");
        Files.copy(script, backup, StandardCopyOption.REPLACE_EXISTING);

        Path tmp = script.resolveSibling(script.getFileName().toString() + ".rewrite.tmp");
        int totalReplacements = 0;
        Map<String, Integer> perToken = new LinkedHashMap<>();
        for (String tok : ALIAS_ORDER) perToken.put(tok, 0);
        List<String> stripped = new ArrayList<>();
        Set<String> uniqueWarnings = new java.util.LinkedHashSet<>();
        long lineCount = 0;
        LegacyTextTypeRewriter textTypes = new LegacyTextTypeRewriter();

        try (BufferedReader reader = Files.newBufferedReader(script, StandardCharsets.UTF_8);
             BufferedWriter writer = Files.newBufferedWriter(tmp, StandardCharsets.UTF_8)) {
            String line;
            while ((line = reader.readLine()) != null) {
                lineCount++;

                // Category C — strip CREATE AGGREGATE lines (class cannot be resolved in isolated
                // classloader; Semoss re-registers SMSS_MEDIAN on first connection).
                Matcher agg = CREATE_AGGREGATE.matcher(line);
                if (agg.matches()) {
                    String aggName = agg.group("name").replace("\"", "");
                    String aggClass = agg.group("class");
                    stripped.add(aggName + " -> " + aggClass);
                    uniqueWarnings.add("Stripped CREATE AGGREGATE " + aggName + " (class "
                            + aggClass + "); Semoss re-registers it on first connection");
                    // Write a comment instead of the DDL so line numbers stay aligned
                    writer.write("-- [migration] stripped: " + line);
                    writer.newLine();
                    continue;
                }

                // Category A + B ROW — token rewrites outside quoted regions
                RewriteResult rr = rewriteLine(line, textTypes);
                totalReplacements += rr.replacements;
                for (var e : rr.perToken.entrySet()) {
                    perToken.merge(e.getKey(), e.getValue(), Integer::sum);
                }

                // Observation-only patterns (warnings for human review)
                for (var o : OBSERVATION_PATTERNS.entrySet()) {
                    if (o.getKey().matcher(line).find()) {
                        uniqueWarnings.add(o.getValue());
                    }
                }

                writer.write(rr.text);
                writer.newLine();
            }
        }

        Files.move(tmp, script, StandardCopyOption.REPLACE_EXISTING);

        boolean changed = totalReplacements > 0 || !stripped.isEmpty();
        if (!changed) {
            Files.deleteIfExists(backup);
            LOGGER.debug("ScriptRewriter: no rewrites applied to " + script.getFileName());
        } else {
            LOGGER.info("ScriptRewriter applied " + totalReplacements
                    + " type-alias replacement(s) and stripped " + stripped.size()
                    + " aggregate(s) in " + script.getFileName());
        }

        // Drop zero-count tokens from the report to keep JSON concise
        perToken.values().removeIf(v -> v == 0);

        long size = Files.exists(script) ? Files.size(script) : 0;
        return new RewriteReport(
                totalReplacements,
                perToken,
                stripped,
                new ArrayList<>(uniqueWarnings),
                size,
                lineCount);
    }

    /**
     * Rewrite a single SQL line, preserving single-quoted strings and double-quoted
     * identifiers verbatim. Returns both the transformed text and per-token counts.
     */
    static RewriteResult rewriteLine(String line) {
        return rewriteLine(line, new LegacyTextTypeRewriter());
    }

    private static RewriteResult rewriteLine(String line, LegacyTextTypeRewriter textTypes) {
        RewriteResult text = textTypes.rewrite(line);
        RewriteResult other = rewriteOtherAliases(text.text());
        Map<String, Integer> counts = new LinkedHashMap<>(text.perToken());
        other.perToken().forEach((key, value) -> counts.merge(key, value, Integer::sum));
        return new RewriteResult(other.text(), text.replacements() + other.replacements(), counts);
    }

    private static RewriteResult rewriteOtherAliases(String line) {
        StringBuilder out = new StringBuilder(line.length());
        int i = 0;
        int replacements = 0;
        Map<String, Integer> perToken = new LinkedHashMap<>();
        int n = line.length();

        while (i < n) {
            char c = line.charAt(i);

            if (c == '\'' || c == '"') {
                int end = findClosingQuote(line, i, c);
                out.append(line, i, end + 1);
                i = end + 1;
                continue;
            }

            int segStart = i;
            while (i < n && line.charAt(i) != '\'' && line.charAt(i) != '"') {
                i++;
            }
            String segment = line.substring(segStart, i);
            SegmentResult sr = applyAliases(segment);
            out.append(sr.text);
            replacements += sr.replacements;
            for (var e : sr.perToken.entrySet()) {
                perToken.merge(e.getKey(), e.getValue(), Integer::sum);
            }
        }

        return new RewriteResult(out.toString(), replacements, perToken);
    }

    /**
     * Find the index of the matching closing quote, accounting for SQL's doubled-quote
     * escape ({@code ''} inside a string, {@code ""} inside a double-quoted identifier).
     * If the string is unterminated (malformed script), returns the end of the line so
     * the rest of the line is treated as inside-quotes and left untouched.
     */
    static int findClosingQuote(String line, int openIdx, char quote) {
        int i = openIdx + 1;
        int n = line.length();
        while (i < n) {
            char c = line.charAt(i);
            if (c == quote) {
                if (i + 1 < n && line.charAt(i + 1) == quote) {
                    i += 2;
                    continue;
                }
                return i;
            }
            i++;
        }
        return n - 1;
    }

    private static SegmentResult applyAliases(String segment) {
        String current = segment;
        int replacements = 0;
        Map<String, Integer> perToken = new LinkedHashMap<>();
        for (Map.Entry<Pattern, String> entry : TYPE_ALIASES.entrySet()) {
            Matcher matcher = entry.getKey().matcher(current);
            int count = 0;
            StringBuilder sb = new StringBuilder();
            while (matcher.find()) {
                matcher.appendReplacement(sb, Matcher.quoteReplacement(entry.getValue()));
                count++;
            }
            matcher.appendTail(sb);
            if (count > 0) {
                current = sb.toString();
                replacements += count;
                perToken.merge(tokenFor(entry.getKey()), count, Integer::sum);
            }
        }
        return new SegmentResult(current, replacements, perToken);
    }

    record RewriteResult(String text, int replacements, Map<String, Integer> perToken) {
        /** Backward-compatible 2-arg convenience for {@link ScriptRewriterTest}. */
        RewriteResult(String text, int replacements) {
            this(text, replacements, Collections.emptyMap());
        }
    }

    private record SegmentResult(String text, int replacements, Map<String, Integer> perToken) {
    }
}
