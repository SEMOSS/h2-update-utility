package org.semoss.h2.migration;

import java.io.BufferedReader;
import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

/**
 * Rewrites an H2 1.x SCRIPT TO dump so that legacy data-type aliases H2 2.x no longer
 * recognises are translated to their modern equivalents before RUNSCRIPT FROM ... FROM_1X.
 *
 * <p>Covers Category A of the migration failure-mode catalog: removed / renamed data types.
 * Replacements are applied only outside single-quoted string literals and double-quoted
 * identifiers, so user data and column names matching a legacy type name are preserved.
 */
public final class ScriptRewriter {

    private static final Logger LOGGER = LogManager.getLogger(ScriptRewriter.class);

    /**
     * Legacy → modern type token replacements. Order is not significant because each
     * pattern is anchored with word boundaries and patterns do not overlap.
     *
     * <p>{@code IDENTITY} uses a negative look-ahead so the {@code IDENTITY()} function
     * (also removed in 2.x but not a type) is left alone — {@code MODE=LEGACY} handles
     * the function case. All other replacements use plain word boundaries.
     */
    static final Map<Pattern, String> TYPE_ALIASES = buildAliasMap();

    private static Map<Pattern, String> buildAliasMap() {
        Map<Pattern, String> m = new LinkedHashMap<>();
        int flags = Pattern.CASE_INSENSITIVE;
        m.put(Pattern.compile("\\bDATETIME\\b", flags), "TIMESTAMP");
        m.put(Pattern.compile("\\bLONGVARCHAR\\b", flags), "VARCHAR");
        m.put(Pattern.compile("\\bLONGVARBINARY\\b", flags), "VARBINARY");
        m.put(Pattern.compile("\\bLONGTEXT\\b", flags), "CLOB");
        m.put(Pattern.compile("\\bMEDIUMTEXT\\b", flags), "VARCHAR");
        m.put(Pattern.compile("\\bTINYTEXT\\b", flags), "VARCHAR");
        m.put(Pattern.compile("\\bNTEXT\\b", flags), "VARCHAR");
        m.put(Pattern.compile("\\bMEDIUMBLOB\\b", flags), "BLOB");
        m.put(Pattern.compile("\\bTINYBLOB\\b", flags), "BLOB");
        m.put(Pattern.compile("\\bNUMBER\\b", flags), "NUMERIC");
        m.put(Pattern.compile("\\bIDENTITY\\b(?!\\s*\\()", flags),
                "BIGINT GENERATED BY DEFAULT AS IDENTITY");
        return m;
    }

    private ScriptRewriter() {
    }

    /**
     * Rewrite the script in place, writing the transformed output back to the same path.
     * A {@code .bak} sibling is created so the original export is preserved.
     *
     * @param script path to the SCRIPT TO output
     * @return number of replacements applied across all aliases
     * @throws IOException if the file cannot be read or written
     */
    public static int rewriteInPlace(Path script) throws IOException {
        Path backup = script.resolveSibling(script.getFileName().toString() + ".pre-rewrite.bak");
        Files.copy(script, backup, StandardCopyOption.REPLACE_EXISTING);

        Path tmp = script.resolveSibling(script.getFileName().toString() + ".rewrite.tmp");
        int totalReplacements = 0;

        try (BufferedReader reader = Files.newBufferedReader(script, StandardCharsets.UTF_8);
             BufferedWriter writer = Files.newBufferedWriter(tmp, StandardCharsets.UTF_8)) {
            String line;
            while ((line = reader.readLine()) != null) {
                RewriteResult rr = rewriteLine(line);
                totalReplacements += rr.replacements;
                writer.write(rr.text);
                writer.newLine();
            }
        }

        Files.move(tmp, script, StandardCopyOption.REPLACE_EXISTING);

        if (totalReplacements > 0) {
            LOGGER.info("ScriptRewriter applied " + totalReplacements
                    + " type-alias replacement(s) to " + script.getFileName());
        } else {
            LOGGER.debug("ScriptRewriter: no legacy type aliases found in " + script.getFileName());
            Files.deleteIfExists(backup);
        }

        return totalReplacements;
    }

    /**
     * Rewrite a single SQL line, preserving single-quoted strings and double-quoted
     * identifiers verbatim.
     */
    static RewriteResult rewriteLine(String line) {
        StringBuilder out = new StringBuilder(line.length());
        int i = 0;
        int replacements = 0;
        int n = line.length();

        while (i < n) {
            char c = line.charAt(i);

            if (c == '\'' || c == '"') {
                int end = findClosingQuote(line, i, c);
                out.append(line, i, end + 1);
                i = end + 1;
                continue;
            }

            int segStart = i;
            while (i < n && line.charAt(i) != '\'' && line.charAt(i) != '"') {
                i++;
            }
            String segment = line.substring(segStart, i);
            SegmentResult sr = applyAliases(segment);
            out.append(sr.text);
            replacements += sr.replacements;
        }

        return new RewriteResult(out.toString(), replacements);
    }

    /**
     * Find the index of the matching closing quote, accounting for SQL's doubled-quote
     * escape ({@code ''} inside a string, {@code ""} inside a double-quoted identifier).
     * If the string is unterminated (malformed script), returns the end of the line so
     * the rest of the line is treated as inside-quotes and left untouched.
     */
    static int findClosingQuote(String line, int openIdx, char quote) {
        int i = openIdx + 1;
        int n = line.length();
        while (i < n) {
            char c = line.charAt(i);
            if (c == quote) {
                if (i + 1 < n && line.charAt(i + 1) == quote) {
                    i += 2;
                    continue;
                }
                return i;
            }
            i++;
        }
        return n - 1;
    }

    private static SegmentResult applyAliases(String segment) {
        String current = segment;
        int replacements = 0;
        for (Map.Entry<Pattern, String> entry : TYPE_ALIASES.entrySet()) {
            Matcher matcher = entry.getKey().matcher(current);
            int count = 0;
            StringBuilder sb = new StringBuilder();
            while (matcher.find()) {
                matcher.appendReplacement(sb, Matcher.quoteReplacement(entry.getValue()));
                count++;
            }
            matcher.appendTail(sb);
            if (count > 0) {
                current = sb.toString();
                replacements += count;
            }
        }
        return new SegmentResult(current, replacements);
    }

    record RewriteResult(String text, int replacements) {
    }

    private record SegmentResult(String text, int replacements) {
    }
}
